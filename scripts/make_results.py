#!/usr/bin/env python3
import json
import logging
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")

TEMPLATE = """# Results sheet
Generated by `scripts/make_results.py` from JSON files. Do not edit numbers by hand.

| Metric | Source | Value | Status |
|---|---|---|---|
| Per-class precision/recall/mAP (grouped test split) | docs/test_metrics.json | {test_metrics_val} | {test_metrics_status} |
| Same on Chennai photo set | docs/chennai_ood_metrics.json | {chennai_metrics_val} | {chennai_metrics_status} |
| Own photos with usable EXIF GPS | docs/exif_audit.json | {exif_audit_val} | {exif_audit_status} |
| Quality-gate rejection rate / agreement | own photo set | | NOT YET MEASURED |
| Dedup precision/recall (labelled pairs) | hand-labelled pairs | | NOT YET MEASURED |
| Severity agreement vs experts (Cohen's kappa) | rating sheets | | NOT YET MEASURED |
| Priority top-N stability | PriorityStabilityTest | | NOT YET MEASURED |
| Proof-of-visit accuracy (real pairs) | field pairs | | NOT YET MEASURED |
| Photo upload to ranked ticket time | benchmark | | NOT YET MEASURED |
| JUnit test count and coverage | mvn verify | | NOT YET MEASURED |
"""

def extract_yolo_metrics(json_path: Path):
    if not json_path.exists():
        return "", "NOT YET MEASURED"
        
    try:
        with open(json_path, 'r') as f:
            data = json.load(f)
            
        overall = data.get("overall", {})
        if not overall:
            return "", "NOT YET MEASURED"
            
        p = overall.get("precision", 0)
        r = overall.get("recall", 0)
        map50 = overall.get("mAP50", 0)
        
        return f"P: {p:.3f}, R: {r:.3f}, mAP@.5: {map50:.3f}", "MEASURED"
    except Exception:
        return "", "NOT YET MEASURED"

def extract_exif_audit(json_path: Path):
    if not json_path.exists():
        return "", "NOT YET MEASURED"
        
    try:
        with open(json_path, 'r') as f:
            data = json.load(f)
            
        total = data.get("total_images", 0)
        if total == 0:
            return "", "NOT YET MEASURED"
            
        usable = data.get("usable_gps", 0)
        pct = (usable / total) * 100
        return f"{usable}/{total} ({pct:.1f}%)", "MEASURED"
    except Exception:
        return "", "NOT YET MEASURED"

def generate_results(docs_dir: Path):
    test_metrics_val, test_metrics_status = extract_yolo_metrics(docs_dir / "test_metrics.json")
    chennai_metrics_val, chennai_metrics_status = extract_yolo_metrics(docs_dir / "chennai_ood_metrics.json")
    exif_audit_val, exif_audit_status = extract_exif_audit(docs_dir / "exif_audit.json")
    
    content = TEMPLATE.format(
        test_metrics_val=test_metrics_val, test_metrics_status=test_metrics_status,
        chennai_metrics_val=chennai_metrics_val, chennai_metrics_status=chennai_metrics_status,
        exif_audit_val=exif_audit_val, exif_audit_status=exif_audit_status
    )
    
    with open(docs_dir / "RESULTS.md", "w") as f:
        f.write(content)
        
    logging.info("Regenerated docs/RESULTS.md")

if __name__ == "__main__":
    generate_results(Path("docs"))
